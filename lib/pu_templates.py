"""
PU訴求軸テンプレート（診断グループ × 軸）

在庫ゼロでも下書きを出して"相談"を減らす。
重要：PUは「診断グループ」ごとにユーザーの心理が違うので、型もグループ別にする。
  - 方法系：まだやり方を探してる → 「自分に合う方法が知りたい？」
  - 薬系  ：もう商品/薬を認知済み(商標) → 「その薬、自分に合う？安く続けたい？」
  - 選択系：クリニック/商品を選んでる最中 → 「ぴったりのを見つけたい？」
問いかけ型（「〜？」）に統一（PU文言フォーマットルール準拠）。
"""

from __future__ import annotations

# 診断グループ → 軸 → テンプレ
# 方法系/選択系は {x} にジャンル名詞が入る。薬系は商品認知済み前提なので名詞不要。
TEMPLATES = {
    "方法診断": {
        "method": ["自分に合った{x}の方法が知りたい？", "結局、{x}はどうするのが正解か知りたい？"],
        "cost": ["{x}、できるだけ費用を抑えたい？", "なるべく安く{x}を始めたい？"],
        "choice": ["自分にぴったりの{x}の方法を見つけたい？"],
        "anxiety": ["{x}、今のやり方で本当に大丈夫…？"],
        "benefit": ["{x}で、なりたい自分になりたい？"],
    },
    "薬診断": {
        "method": ["その薬、自分に合う使い方で効果を出したい？", "正しい飲み方で効果を最大にしたい？"],
        "cost": ["その薬、できるだけ安く続けたい？"],
        "choice": ["結局どの薬が自分に合うか知りたい？"],
        "anxiety": ["その薬、副作用なく続けられるか不安…？"],
        "benefit": ["しっかり結果を出して自信をつけたい？"],
    },
    "集客診断": {
        "choice": ["自分にぴったりの{x}を見つけたい？", "どの{x}が自分に合うか見極めたい？"],
        "cost": ["できるだけ費用を抑えて{x}を選びたい？"],
        "method": ["自分に合った{x}の選び方を知りたい？"],
        "anxiety": ["{x}選びで失敗したくない…？"],
        "benefit": ["ぴったりの{x}で理想を叶えたい？"],
    },
}

# ジャンル → (方法系で使う名詞, 選択系で使う名詞)
GENRE_NOUN = {
    "医療ダイエット(GLP-1)": ("ダイエット", "クリニック"),
    "包茎手術": ("包茎治療", "クリニック"),
    "ED": ("ED治療", "クリニック"),
    "オンラインピル": ("ピル", "ピル"),
    "AGA": ("薄毛治療", "クリニック"),
    "FAGA": ("薄毛治療", "クリニック"),
    "ほくろ除去": ("ほくろ除去", "クリニック"),
    "いびき": ("いびき対策", "対策"),
    "リカバリーウェア": ("リカバリーウェア", "リカバリーウェア"),
}


def template_pu(genre_label: str, group: str | None, axis: str) -> list[str]:
    """診断グループ×軸からPU文言の下書きを作る（無理なら空リスト）"""
    if not group:
        return []
    patterns = TEMPLATES.get(group, {}).get(axis, [])
    if not patterns:
        return []
    if group == "薬診断":  # 名詞差し込み不要
        return list(patterns)
    nouns = GENRE_NOUN.get(genre_label)
    if not nouns:
        return []
    noun = nouns[1] if group == "集客診断" else nouns[0]
    return [p.format(x=noun) for p in patterns]
